def _build_consensus(**models):
    """Pack sub-model outputs into a JSON dict. Only includes models with data."""
    result = {}
    for name, (action, reasoning) in models.items():
        if action or reasoning:
            result[name] = {"action": action or "HOLD", "reasoning": reasoning or ""}
